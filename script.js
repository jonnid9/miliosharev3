    result = templates.extension
      .replaceAll('{PAKET}', data.title)
      .replaceAll('{SERVER_INFO}', data.serverInfo)
      .replaceAll('{LINK_EXT}', linkExt)
      .replaceAll('{LINK_APK}', linkApk)
      .replaceAll('{LINK_KIWI}', linkKiwi)
